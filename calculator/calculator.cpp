using namespace std;

/**
 * @brief Выполняет сложение двух чисел.
 *
 * Выводит в консоль результат сложения двух целых чисел.
 *
 * @param a Первое число.
 * @param b Второе число.
 */
void sum(int a, int b)
{
    cout << "Результат сложения: " << a + b << endl;
}

/**
 * @brief Выполняет вычитание двух чисел.
 *
 * Вычитает второе число из первого и выводит результат в консоль.
 *
 * @param a Уменьшаемое.
 * @param b Вычитаемое.
 */
void ras(int a, int b)
{
    cout << "Результат разности: " << a - b << endl;
}

/**
 * @brief Выполняет умножение двух чисел.
 *
 * Выводит в консоль результат умножения двух целых чисел.
 *
 * @param a Первый множитель.
 * @param b Второй множитель.
 */
void pros(int a, int b)
{
    cout << "Результат умножения: " << a * b << endl;
}

/**
 * @brief Выполняет деление двух чисел.
 *
 * Если делитель не равен нулю, выводит результат целочисленного
 * деления первого числа на второе. Если делитель равен нулю,
 * выводит сообщение об ошибке.
 *
 * @param a Делимое.
 * @param b Делитель.
 */
void del(int a, int b)
{
    if (b != 0)
    {
        cout << "Результат деления: " << a / b << endl;
    }
    else
    {
        cout << "Деление на ноль невозможно!\n";
    }
}

/**
 * @brief Выполняет операцию инкремента выбранного числа.
 *
 * Предлагает пользователю выбрать первое или второе число,
 * увеличивает выбранное значение на единицу и выводит значение
 * до и после операции. Позволяет повторять операцию.
 *
 * @param a Первое число.
 * @param b Второе число.
 */
void unar_plus(int a, int b)
{
    int ch = 0;
    cout << "Выберите число:\n";
    cout << "1. Первое число\n";
    cout << "2. Второе число\n";
    cin >> ch;

    if (ch == 1)
    {
        while (true)
        {
            cout << "\nВаше число до операции: " << a;
            a++;
            cout << "\nВаше число после операции: " << a;

            cout << "\nХотите продолжить? (1 - да, 2 - нет): ";
            cin >> ch;

            if (ch == 2)
                break;
        }
    }
    else if (ch == 2)
    {
        while (true)
        {
            cout << "\nВаше число до операции: " << b;
            b++;
            cout << "\nВаше число после операции: " << b;

            cout << "\nХотите продолжить? (1 - да, 2 - нет): ";
            cin >> ch;

            if (ch == 2)
                break;
        }
    }
}

